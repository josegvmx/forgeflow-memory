/**
 * Retrieval eval (R14 phase 3): the golden set against the stored events, per strategy.
 *
 *   npm run eval:retrieval [-- --golden tests/evals/fixtures/golden-sim.json] [--strategies vector,hybrid]
 *   npm run eval:retrieval -- --spaces voyage-code-2:default,voyage-code-2:no-scenario
 *
 * Without --spaces: the live column (reasoning_events.embedding, HNSW) with the service's model.
 * With --spaces: each (model, variant) filled by `npm run embed:variant`, searched exactly; spaces not
 * filled are skipped with a warning. Writes docs/retrieval-eval[-spaces].md (tables) and .json (per query).
 * Needs DATABASE_URL (the store holding the imported sim export) and the embedding key(s).
 * The gate on these numbers: npm run test:eval (tests/evals/retrieval.eval.ts).
 */
import 'dotenv/config';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import db from '../src/store/client.js';
import { embeddingModel } from '../src/ingest/embedder.js';
import { STRATEGIES, type Strategy, type EmbeddingSpace } from '../src/retrieval/strategies.js';
import { resultsMarkdown } from '../src/eval/retrievalMetrics.js';
import { runRetrievalEval } from '../src/eval/runRetrieval.js';
import type { GoldenSimSet } from '../src/eval/goldenSim.js';

const argv = process.argv.slice(2);
const opt = (f: string) => { const i = argv.indexOf(f); return i >= 0 ? argv[i + 1] : undefined; };
const golden: GoldenSimSet = JSON.parse(readFileSync(resolve(process.cwd(), opt('--golden') ?? 'tests/evals/fixtures/golden-sim.json'), 'utf8'));
const strategies = (opt('--strategies')?.split(',') ?? [...STRATEGIES]) as Strategy[];
for (const s of strategies) if (!STRATEGIES.includes(s)) { console.error(`unknown strategy ${s} (${STRATEGIES.join(', ')})`); process.exit(2); }
const spaceArg = opt('--spaces');
const spaces: Array<EmbeddingSpace | undefined> = spaceArg
  ? spaceArg.split(',').map(x => { const [model, variant = 'default'] = x.split(':'); return { model, variant }; })
  : [undefined];

let run;
try {
  run = await runRetrievalEval({ golden, strategies, spaces, log: line => console.log(line) });
} catch (err) {
  console.error(err instanceof Error ? err.message : String(err));
  await db.end();
  process.exit(2);
}
if (run.empty.length) console.warn(`⚠ ${run.empty.length} queries have no relevant events in this store (import missing?): ${run.empty.join(', ')}`);
for (const s of run.skipped) console.warn(`⚠ skipped ${s}`);

const md = resultsMarkdown(run.summary, { model: spaceArg ? `per row (${spaceArg})` : embeddingModel(), queries: golden.queries.length, date: new Date().toISOString().slice(0, 10), simCommit: golden.simCommit });
const caveats = [
  '- **structured** reads ids, cycles and the kind of event from the question (src/retrieval/questionHints.ts).',
  '  Its rules were written knowing the golden set\'s question templates, so its numbers here are optimistic;',
  '  on 11 paraphrases outside the golden set the event-type rules first got 9 right (now 11, so no longer held out).',
  '- **machine-history** is easy for any strategy that filters by machine and event type: every such event is relevant.',
  '- **vague** questions name no machine, cycle or part; they are reported, not gated.',
  ...(run.skipped.length ? [`- Skipped spaces (not filled): ${run.skipped.map(s => s.split(':')[0]).join(', ')}.`] : []),
].join('\n');
mkdirSync('docs', { recursive: true });
const out = spaceArg ? 'docs/retrieval-eval-spaces' : 'docs/retrieval-eval';
writeFileSync(`${out}.md`, `# Retrieval eval (golden-sim)${spaceArg ? ': embedding models and text variants' : ''}\n\nGenerated by \`npm run eval:retrieval\`; see src/eval/retrievalMetrics.ts for the definitions.\n\n${caveats}\n\n${md}`);
writeFileSync(`${out}.json`, JSON.stringify({ spaces: spaceArg ?? embeddingModel(), simCommit: golden.simCommit, summary: run.summary, perQuery: run.perQuery, relevant: run.relevant, skipped: run.skipped }, null, 2) + '\n');
console.log('\n' + md + `\nWritten: ${out}.md, ${out}.json`);
await db.end();
